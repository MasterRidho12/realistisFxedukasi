export type PairKey = 'ALL' | 'XAUUSD' | 'EURUSD' | 'USDJPY' | 'GBPUSD' | 'AUDUSD';

export interface BacktestTrade {
  id: string;
  pair: string;
  pairKey: 'XAUUSD' | 'EURUSD' | 'USDJPY' | 'GBPUSD' | 'AUDUSD';
  year: number;
  date: string;
  session: string;
  timeframe: string;
  type: 'BUY BREAKOUT' | 'SELL BREAKDOWN' | 'BUY SNR RETEST' | 'SELL SNR REJECTION';
  strategyType: 'BREAKOUT_MOMENTUM' | 'SNR_KEY_RETEST';
  keySnrLevel: string;
  entryPrice: string;
  stopLoss: string;
  takeProfit1: string;
  takeProfit2: string;
  exitPrice: string;
  pips: number;
  pipsFormatted: string;
  outcome: 'HIT_TP2' | 'HIT_TP1' | 'HIT_RUNNER' | 'HIT_SL';
  aiConfidence: number; // e.g. 94%
  aiAnalysis: string;
  tradingViewRef: string;
}

export interface MonthlyPipsRow {
  year: number;
  months: {
    month: string;
    pips: number;
    winRate: number;
    trades: number;
  }[];
  totalPips: number;
  winRate: number;
  totalTrades: number;
}

export interface DailyStats {
  avgPipsPerDay: number;
  bestDayPips: number;
  bestDayDate: string;
  maxDailyLossPips: number;
  winRateDaysPct: number;
  avgTradesPerDay: number;
  pipsDistribution: {
    range: string;
    count: number;
    percentage: number;
  }[];
}

export interface YearlyStats {
  year: number;
  pips: number;
  winRate: number;
  trades: number;
  winningTrades: number;
  losingTrades: number;
  profitFactor: number;
  maxDrawdownPct: number;
}

export interface EquityCurvePoint {
  date: string;
  timestamp: string;
  year: number;
  cumulativePips: number;
  milestone?: string;
  pairPips: Record<string, number>;
}

export interface PairMetrics {
  pair: PairKey;
  name: string;
  symbol: string;
  badge: string;
  color: string;
  description: string;
  winRate: number;
  totalTrades: number;
  winningTrades: number;
  losingTrades: number;
  totalPips: number;
  profitFactor: number;
  maxDrawdownPct: number;
  avgRiskReward: string;
  sharpeRatio: number;
  avgDailyPips: number;
  avgMonthlyPips: number;
  bestYear: string;
  strategySummary: string;
  yearlyStats: YearlyStats[];
  monthlyData: MonthlyPipsRow[];
  dailyStats: DailyStats;
  equityCurve: EquityCurvePoint[];
  trades: BacktestTrade[];
}

